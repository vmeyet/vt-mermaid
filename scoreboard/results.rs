//! The committed results: one JSON file per input, so a diff names each input that changed, and the summary tables.

use std::collections::BTreeMap;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::expected::{Expected, Kind};
use crate::metrics::{Drawn, Metrics, float};
use crate::tool::{Status, Tool};

/// Every tool's metrics on one input, by tool name then width.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub(crate) struct InputResult {
    pub(crate) input: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub(crate) expected: Option<Counts>,
    pub(crate) tools: BTreeMap<String, BTreeMap<u16, Metrics>>,
}

/// What the oracle says a drawing must show.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub(crate) struct Counts {
    pub(crate) node_labels: usize,
    pub(crate) edge_labels: usize,
    pub(crate) arrows: usize,
}

/// Wall times in milliseconds, by tool and width, for the tools run this time.
pub(crate) type Times = BTreeMap<(Tool, u16), Vec<u64>>;

impl Counts {
    pub(crate) fn of(expected: &Expected) -> Self {
        Self { node_labels: expected.node_labels.len(), edge_labels: expected.edge_labels.len(), arrows: expected.arrows }
    }
}

impl InputResult {
    /// The fresh metrics on top of the ones on disk, so a tool not run this time keeps its last results.
    pub(crate) fn merged(
        folder: &Path,
        input: &str,
        expected: Option<Counts>,
        fresh: BTreeMap<String, BTreeMap<u16, Metrics>>,
    ) -> io::Result<Self> {
        let mut tools = match fs::read_to_string(file(folder, input)) {
            Ok(json) => serde_json::from_str::<Self>(&json).map_err(io::Error::other)?.tools,
            Err(error) if error.kind() == io::ErrorKind::NotFound => BTreeMap::new(),
            Err(error) => return Err(error),
        };
        tools.extend(fresh);
        Ok(Self { input: input.to_owned(), expected, tools })
    }

    pub(crate) fn write(&self, folder: &Path) -> io::Result<()> {
        fs::write(file(folder, &self.input), self.json().map_err(io::Error::other)?)
    }

    /// Indented down to each tool and width, each metrics on one line: a change shows as the lines of what changed.
    fn json(&self) -> serde_json::Result<String> {
        let mut json = format!("{{\n  \"input\": {},\n", serde_json::to_string(&self.input)?);
        if let Some(expected) = &self.expected {
            json.push_str(&format!("  \"expected\": {},\n", serde_json::to_string(expected)?));
        }
        let mut tools = Vec::new();
        for (tool, widths) in &self.tools {
            let widths = widths
                .iter()
                .map(|(width, metrics)| Ok(format!("      \"{width}\": {}", serde_json::to_string(metrics)?)))
                .collect::<serde_json::Result<Vec<_>>>()?;
            tools.push(format!("    {}: {{\n{}\n    }}", serde_json::to_string(tool)?, widths.join(",\n")));
        }
        json.push_str(&format!("  \"tools\": {{\n{}\n  }}\n}}\n", tools.join(",\n")));
        Ok(json)
    }

    pub(crate) fn metrics(&self, tool: Tool, width: u16) -> Option<&Metrics> {
        self.tools.get(tool.name()).and_then(|widths| widths.get(&width))
    }
}

fn file(folder: &Path, input: &str) -> PathBuf {
    let name = Path::new(input).file_stem().map_or_else(|| input.to_owned(), |stem| stem.to_string_lossy().into_owned());
    folder.join(name + ".json")
}

/// The summary page: per width, a table per tool over every input, one over the inputs every tool drew, and vt-mermaid's exact counts.
pub(crate) fn summary(results: &[InputResult], widths: &[u16], times: &Times, kind: Kind, sample: Option<usize>) -> String {
    let (command, readme) = match kind {
        Kind::Flowchart => ("", "../README.md"),
        Kind::Sequence => (" -- --kind sequence", "../../README.md"),
        Kind::State => (" -- --kind state", "../../README.md"),
        Kind::Class => (" -- --kind class", "../../README.md"),
    };
    let mut page = format!(
        "# Scoreboard results\n\nGenerated by `cargo run --release --example scoreboard{command}`; [`README.md`]({readme}) defines every column.\n"
    );
    let oracle = results.iter().filter(|result| result.expected.is_some()).count();
    let noun = kind.noun();
    let scope = sample.map_or_else(|| format!("every {noun} in the corpus"), |every| format!("a sample, one {noun} in {every}"));
    page.push_str(&format!("{} inputs, {scope}; {oracle} of them have an oracle meaning.\n", results.len()));
    for &width in widths {
        page.push_str(&format!("\n## {width} columns\n\n{}", tools_table(results, width, times)));
        page.push_str(&format!("\n{}", common_table(results, width)));
    }
    if kind.measured() {
        page.push_str(&format!("\n## vt-mermaid exact\n\n{}", exact_table(results, widths)));
    }
    page
}

fn tools_table(results: &[InputResult], width: u16, times: &Times) -> String {
    let mut table = String::from(
        "| Tool | Rendered | Refused | Crashed | Timed out | Fits | Node labels | Edge labels | Arrows right | Score | Median ms | p95 ms |\n|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n",
    );
    for tool in Tool::ALL {
        let all: Vec<&Metrics> = results.iter().filter_map(|result| result.metrics(tool, width)).collect();
        if all.is_empty() {
            continue;
        }
        let with_oracle: Vec<(&Metrics, Counts)> =
            results.iter().filter_map(|result| Some((result.metrics(tool, width)?, result.expected?))).collect();
        let status = |status| all.iter().filter(|metrics| metrics.status == status).count();
        let fits = all.iter().filter(|metrics| metrics.drawn.is_some_and(|drawn| drawn.fits)).count();
        let node_labels = mean_share(&with_oracle, |drawn| drawn.node_labels, |counts| counts.node_labels);
        let edge_labels = mean_share(&with_oracle, |drawn| drawn.edge_labels, |counts| counts.edge_labels);
        let arrows_right = percent(
            with_oracle.iter().filter(|(metrics, counts)| metrics.drawn.is_some_and(|drawn| drawn.arrows == counts.arrows)).count(),
            with_oracle.len(),
        );
        let scores: Vec<usize> = with_oracle.iter().filter_map(|(metrics, _)| metrics.score).map(|score| score as usize).collect();
        let score = mean(scores.iter().copied(), scores.len());
        let (median, p95) =
            times.get(&(tool, width)).map_or_else(|| ("–".to_owned(), "–".to_owned()), |times| (quantile(times, 50), quantile(times, 95)));
        table.push_str(&format!(
            "| {} {} | {} | {} | {} | {} | {fits} | {node_labels} | {edge_labels} | {arrows_right} | {score} | {median} | {p95} |\n",
            tool.name(),
            tool.version(),
            status(Status::Rendered),
            status(Status::Refused),
            status(Status::Crashed),
            status(Status::TimedOut),
        ));
    }
    table
}

/// Layout compared where it can be: only on the inputs every tool on the board drew.
/// A tool that draws none of the inputs, as mermaid-ascii draws no state diagram, is left out of it.
fn common_table(results: &[InputResult], width: u16) -> String {
    let draws_any = |tool: Tool| results.iter().any(|result| result.metrics(tool, width).is_some_and(|metrics| metrics.drawn.is_some()));
    let tools: Vec<Tool> = Tool::ALL.into_iter().filter(|&tool| draws_any(tool)).collect();
    let common: Vec<&InputResult> = results
        .iter()
        .filter(|result| {
            result.expected.is_some()
                && tools.iter().all(|&tool| result.metrics(tool, width).is_some_and(|metrics| metrics.drawn.is_some()))
        })
        .collect();
    let mut table = format!(
        "On the {} inputs every tool drawing this kind drew:\n\n| Tool | Rows | Area | Crossings | Bends | Score |\n|---|--:|--:|--:|--:|--:|\n",
        common.len()
    );
    for tool in tools {
        let drawn: Vec<_> = common.iter().filter_map(|result| result.metrics(tool, width)?.drawn).collect();
        let scores: Vec<usize> =
            common.iter().filter_map(|result| result.metrics(tool, width)?.score).map(|score| score as usize).collect();
        table.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} |\n",
            tool.name(),
            mean(drawn.iter().map(|drawn| drawn.rows), drawn.len()),
            mean(drawn.iter().map(|drawn| drawn.area), drawn.len()),
            drawn.iter().map(|drawn| drawn.crossings).sum::<usize>(),
            drawn.iter().map(|drawn| drawn.bends).sum::<usize>(),
            mean(scores.iter().copied(), scores.len()),
        ));
    }
    table
}

fn exact_table(results: &[InputResult], widths: &[u16]) -> String {
    let mut table = String::from(
        "| Width | Drawn | Crossings | Crossing glyphs | Bends | Corner glyphs as bends | Edge cells | Cells beside a node | Inputs with violations | Violations |\n|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|\n",
    );
    for &width in widths {
        let measured: Vec<&Metrics> =
            results.iter().filter_map(|result| result.metrics(Tool::VtMermaid, width)).filter(|metrics| metrics.exact.is_some()).collect();
        let exact = measured.iter().filter_map(|metrics| metrics.exact.as_ref());
        let drawn = measured.iter().filter_map(|metrics| metrics.drawn);
        table.push_str(&format!(
            "| {width} | {} | {} | {} | {} | {} | {} | {} | {} | {} |\n",
            measured.len(),
            exact.clone().map(|exact| exact.crossings).sum::<usize>(),
            drawn.clone().map(|drawn| drawn.crossings).sum::<usize>(),
            exact.clone().map(|exact| exact.bends).sum::<usize>(),
            drawn.map(|drawn| drawn.bends).sum::<usize>(),
            exact.clone().map(|exact| exact.edge_cells).sum::<usize>(),
            exact.clone().map(|exact| exact.beside_nodes).sum::<usize>(),
            exact.clone().filter(|exact| !exact.violations.is_empty()).count(),
            exact.map(|exact| exact.violations.len()).sum::<usize>(),
        ));
    }
    table
}

/// The share of labels found, averaged over the inputs that have some, so a 50-node flowchart weighs as much as a 2-node one.
fn mean_share(with_oracle: &[(&Metrics, Counts)], found: impl Fn(Drawn) -> usize, expected: impl Fn(Counts) -> usize) -> String {
    let shares: Vec<f64> = with_oracle
        .iter()
        .filter(|(_, counts)| expected(*counts) > 0)
        .map(|(metrics, counts)| metrics.drawn.map_or(0.0, |drawn| float(found(drawn)) / float(expected(*counts))))
        .collect();
    if shares.is_empty() { "–".to_owned() } else { format!("{:.1}%", shares.iter().sum::<f64>() * 100.0 / float(shares.len())) }
}

fn percent(part: usize, whole: usize) -> String {
    if whole == 0 { "–".to_owned() } else { format!("{:.1}%", float(part) * 100.0 / float(whole)) }
}

fn mean(values: impl Iterator<Item = usize>, count: usize) -> String {
    if count == 0 { "–".to_owned() } else { format!("{:.1}", float(values.sum::<usize>()) / float(count)) }
}

fn quantile(times: &[u64], percent: usize) -> String {
    let mut sorted = times.to_vec();
    sorted.sort_unstable();
    sorted.get((sorted.len() - 1) * percent / 100).map_or_else(|| "–".to_owned(), u64::to_string)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::metrics::Metrics;

    #[test]
    fn the_json_written_reads_back_the_same() {
        let metrics = Metrics { status: Status::Refused, reason: Some("no".to_owned()), drawn: None, score: Some(0), exact: None };
        let result = InputResult {
            input: "flowchart/a.mmd".to_owned(),
            expected: Some(Counts { node_labels: 2, edge_labels: 0, arrows: 1 }),
            tools: BTreeMap::from([("vt-mermaid".to_owned(), BTreeMap::from([(80, metrics.clone()), (100, metrics)]))]),
        };

        assert_eq!(serde_json::from_str::<InputResult>(&result.json().unwrap()).unwrap(), result);
    }
}
